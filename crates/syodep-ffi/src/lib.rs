//! C ABI for the syodep core, consumed by the Qt shell.
//!
//! Conventions:
//!
//! - Every function is `extern "C"` and panic-safe (panics are caught and
//!   reported as errors / no-ops rather than unwinding into C++).
//! - The shell owns one `SyoApp` per window, created with [`syo_app_new`]
//!   and destroyed with [`syo_app_free`].
//! - Strings returned by the core are freed with [`syo_string_free`];
//!   bitmaps with [`syo_bitmap_free`]. Strings passed in are borrowed UTF-8.
//! - Key events arrive as the textual chord syntax from
//!   `syodep_config::keys` (e.g. `j`, `G`, `<C-d>`); the shell performs the
//!   purely mechanical Qt-event-to-string translation.
//!
//! The header `include/syodep_ffi.h` is generated by cbindgen at build time.
//!
//! Safety: this crate is the FFI boundary; all `unsafe` here is confined to
//! pointer/CString handling at the very edge. No MuPDF or Qt types cross
//! this boundary in either direction.

use std::ffi::{c_char, CStr, CString};
use std::panic::{catch_unwind, AssertUnwindSafe};
use std::path::PathBuf;

use syodep_config::keys::parse_sequence;
use syodep_config::Config;
use syodep_core::{App, Effects, HighlightId, HighlightPdfState, TextAnnotationId};
use syodep_storage::Storage;

/// Opaque application handle.
pub struct SyoApp {
    app: App,
    /// Resolved starting directory for the Open dialog (absolute when known).
    open_dir: String,
    /// Human-readable provenance of `open_dir`, reported by `--check`.
    open_dir_source: String,
    /// Canvas background, resolved from `[view] background`.
    background_color: SyoColor,
    /// Highlight for focus mode, from `[view] focus_color`/`focus_opacity`.
    focus_color: SyoColor,
    /// Highlight for the visual selection, from `[view] visual_color`/`visual_opacity`.
    visual_color: SyoColor,
    /// Highlight colour, from `[view] highlight_color`/`highlight_opacity`.
    highlight_color: SyoColor,
    /// Pause before a half-typed sequence resolves, from `[input] timeout_ms`.
    key_timeout_ms: u32,
}

/// An RGBA colour resolved from the config, in 0-255 components.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct SyoColor {
    pub r: u8,
    pub g: u8,
    pub b: u8,
    pub a: u8,
}

/// Resolve a configured `#rrggbb` plus an opacity into RGBA.
///
/// Never fails: an unparseable colour falls back to `fallback` and returns a
/// warning for the status bar, matching the rule that a bad config degrades
/// rather than aborting. Opacity is clamped to 0.0..=1.0 so a typo cannot make
/// the overlay invisible-by-arithmetic in a way that looks like a bug.
fn resolve_color(
    option: &str,
    value: &str,
    opacity: f32,
    fallback: &str,
) -> (SyoColor, Option<String>) {
    let (rgb, warning) = match syodep_config::parse_hex_color(value) {
        Some(rgb) => (rgb, None),
        None => (
            syodep_config::parse_hex_color(fallback).expect("built-in default colours are valid"),
            Some(format!(
                "invalid {option} {value:?} in [view]; using the default {fallback}"
            )),
        ),
    };
    let (r, g, b) = rgb;
    let a = (opacity.clamp(0.0, 1.0) * 255.0).round() as u8;
    (SyoColor { r, g, b, a }, warning)
}

/// Outcome of resolving the Open-dialog starting directory.
struct OpenDirResolution {
    /// Directory the dialog should open in (empty if even the CWD is unknown,
    /// in which case the shell lets Qt pick its own default).
    path: String,
    /// Short note on where the value came from, for `--check`.
    source: String,
    /// A startup warning to surface, set only when a configured directory was
    /// requested but could not be used.
    warning: Option<String>,
}

/// Resolve the Open-dialog starting directory.
///
/// Precedence: a configured `files.open_dir` that exists as a directory wins;
/// otherwise the launch (current working) directory is used. A configured path
/// that is missing or not a directory falls back to the launch directory and
/// produces a warning.
fn resolve_open_dir(configured: Option<&str>) -> OpenDirResolution {
    let cwd = std::env::current_dir()
        .ok()
        .map(|p| p.display().to_string())
        .unwrap_or_default();

    match configured {
        Some(raw) if !raw.trim().is_empty() => {
            if PathBuf::from(raw).is_dir() {
                OpenDirResolution {
                    path: raw.to_owned(),
                    source: format!("config: files.open_dir ({raw})"),
                    warning: None,
                }
            } else {
                OpenDirResolution {
                    path: cwd,
                    source: format!("config dir not found ({raw}) — using launch directory"),
                    warning: Some(format!(
                        "open_dir not found: {raw} — using launch directory"
                    )),
                }
            }
        }
        _ => OpenDirResolution {
            path: cwd,
            source: "launch directory".to_owned(),
            warning: None,
        },
    }
}

/// Effect bits returned by input functions.
pub const SYO_EFFECT_REDRAW: u32 = 1;
pub const SYO_EFFECT_QUIT: u32 = 2;
pub const SYO_EFFECT_OPEN_FILE_DIALOG: u32 = 4;
/// A partial key sequence is buffered. The shell should arm its pause timer
/// (see `syo_app_key_timeout_ms`) and call `syo_app_key_timeout` when it
/// fires; when this bit is clear it should cancel any armed timer.
pub const SYO_EFFECT_PENDING_INPUT: u32 = 8;
/// The document was reloaded from disk (a save rewrote it). Any page bitmaps the
/// shell is caching are stale even though the layout and zoom are unchanged, so
/// it must drop them.
pub const SYO_EFFECT_RELOAD: u32 = 16;
/// Quitting would lose highlights not yet embedded in the PDF. The shell
/// should ask (Save & Quit / Discard & Quit / Cancel) and call
/// `syo_app_quit_save` or `syo_app_quit_discard` with the answer, rather than
/// quitting outright.
pub const SYO_EFFECT_CONFIRM_QUIT: u32 = 32;
/// The annotation collection changed. Distinct from [`SYO_EFFECT_REDRAW`]: a
/// canvas refresh and a sidebar list refresh are different requests.
pub const SYO_EFFECT_ANNOTATIONS_CHANGED: u32 = 64;
/// Show or hide the highlights sidebar and move keyboard focus with it (see
/// `Effects::toggle_highlights_sidebar`). Sidebar visibility is shell state, so
/// this is a toggle request rather than a desired state.
pub const SYO_EFFECT_TOGGLE_HIGHLIGHTS_SIDEBAR: u32 = 128;
/// Show or hide the annotations sidebar page (see
/// `Effects::toggle_annotations_sidebar`).
pub const SYO_EFFECT_TOGGLE_ANNOTATIONS_SIDEBAR: u32 = 256;
/// A pending annotation anchor was captured; open the Annotations page in
/// creation mode (see `Effects::create_annotation_requested`). Never a hide.
pub const SYO_EFFECT_CREATE_ANNOTATION_REQUESTED: u32 = 512;

fn effects_to_bits(effects: Effects) -> u32 {
    let mut bits = 0;
    if effects.redraw {
        bits |= SYO_EFFECT_REDRAW;
    }
    if effects.quit {
        bits |= SYO_EFFECT_QUIT;
    }
    if effects.open_file_dialog {
        bits |= SYO_EFFECT_OPEN_FILE_DIALOG;
    }
    if effects.pending_input {
        bits |= SYO_EFFECT_PENDING_INPUT;
    }
    if effects.reload {
        bits |= SYO_EFFECT_RELOAD;
    }
    if effects.confirm_quit {
        bits |= SYO_EFFECT_CONFIRM_QUIT;
    }
    if effects.annotations_changed {
        bits |= SYO_EFFECT_ANNOTATIONS_CHANGED;
    }
    if effects.toggle_highlights_sidebar {
        bits |= SYO_EFFECT_TOGGLE_HIGHLIGHTS_SIDEBAR;
    }
    if effects.toggle_annotations_sidebar {
        bits |= SYO_EFFECT_TOGGLE_ANNOTATIONS_SIDEBAR;
    }
    if effects.create_annotation_requested {
        bits |= SYO_EFFECT_CREATE_ANNOTATION_REQUESTED;
    }
    bits
}

