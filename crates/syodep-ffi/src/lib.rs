/// Fill `out` with up to `capacity` visible pages; returns the number of
/// visible pages (which may exceed `capacity`; call again with more room).
///
/// # Safety
/// `app` must be valid; `out` must point to at least `capacity` elements.
#[no_mangle]
pub unsafe extern "C" fn syo_app_visible_pages(
    app: *const SyoApp,
    out: *mut SyoVisiblePage,
    capacity: usize,
) -> usize {
    let Some(app) = (unsafe { app.as_ref() }) else {
        return 0;
    };
    let Ok(pages) = catch_unwind(AssertUnwindSafe(|| app.app.visible_pages())) else {
        return 0;
    };
    if !out.is_null() {
        for (i, page) in pages.iter().take(capacity).enumerate() {
            unsafe {
                *out.add(i) = SyoVisiblePage {
                    page: page.page,
                    x: page.rect.x,
                    y: page.rect.y,
                    width: page.rect.width,
                    height: page.rect.height,
                };
            }
        }
    }
    pages.len()
}

/// Collect screen rectangles into a freshly allocated [`SyoOverlay`].
fn overlay_from(rects: Option<Vec<syodep_core::layout::ScreenRect>>) -> SyoOverlay {
    match rects {
        Some(rects) if !rects.is_empty() => {
            let boxed: Box<[SyoRect]> = rects
                .into_iter()
                .map(|r| SyoRect {
                    x: r.x,
                    y: r.y,
                    width: r.width,
                    height: r.height,
                })
                .collect();
            let rect_count = boxed.len();
            let rects = Box::into_raw(boxed) as *const SyoRect;
            SyoOverlay {
                valid: 1,
                rects,
                rect_count,
            }
        }
        _ => invalid_overlay(),
    }
}

/// [`SyoOverlay`] owns a raw pointer and so is not `Copy`; build a fresh
/// "nothing to draw" value wherever one is needed rather than sharing one.
fn invalid_overlay() -> SyoOverlay {
    SyoOverlay {
        valid: 0,
        rects: std::ptr::null(),
        rect_count: 0,
    }
}

/// The focus highlight, one rectangle per spanned visible line. `valid` is 0
/// outside focus mode. One call covers every scope: what the highlight *is* --
/// a character, word, line, sentence or paragraph -- is the core's business,
/// not the shell's. The result must be released with [`syo_overlay_free`].
///
/// # Safety
/// `app` must be valid.
#[no_mangle]
pub unsafe extern "C" fn syo_app_focus(app: *const SyoApp) -> SyoOverlay {
    let Some(app) = (unsafe { app.as_ref() }) else {
        return invalid_overlay();
    };
    catch_unwind(AssertUnwindSafe(|| {
        overlay_from(app.app.focus_screen_rects())
    }))
    .unwrap_or_else(|_| invalid_overlay())
}

/// The visual-mode selection, one rectangle per spanned visible line. `valid`
/// is 0 outside visual mode. The result must be released with
/// [`syo_overlay_free`].
///
/// # Safety
/// `app` must be valid.
#[no_mangle]
pub unsafe extern "C" fn syo_app_selection(app: *const SyoApp) -> SyoOverlay {
    let Some(app) = (unsafe { app.as_ref() }) else {
        return invalid_overlay();
    };
    catch_unwind(AssertUnwindSafe(|| {
        overlay_from(app.app.visual_screen_rects())
    }))
    .unwrap_or_else(|_| invalid_overlay())
}

/// Pending highlights to paint on visible pages, plus the one being placed
/// while highlight mode is active. Embedded records are omitted (MuPDF draws
/// them). Distinct from [`syo_app_highlight_list`], which returns annotation
/// metadata for every stored highlight.
///
/// One call for both pending forms, and one colour, because the shell merges
/// an overlay's rectangles into a single fill — two overlays in the same colour
/// would double-blend wherever a pending highlight overlapped a stored one.
/// The result must be released with [`syo_overlay_free`].
///
/// # Safety
/// `app` must be valid.
#[no_mangle]
pub unsafe extern "C" fn syo_app_highlights(app: *const SyoApp) -> SyoOverlay {
    let Some(app) = (unsafe { app.as_ref() }) else {
        return invalid_overlay();
    };
    catch_unwind(AssertUnwindSafe(|| {
        overlay_from(app.app.highlight_screen_rects())
    }))
    .unwrap_or_else(|_| invalid_overlay())
}

/// Free the `rects` buffer of a [`SyoOverlay`]. A no-op for an invalid overlay,
/// so the shell can call it unconditionally.
///
/// # Safety
/// `overlay` must be a value returned by `syo_app_focus`, `syo_app_selection` or
/// `syo_app_highlights`, not freed before.
#[no_mangle]
pub unsafe extern "C" fn syo_overlay_free(overlay: SyoOverlay) {
    if overlay.rects.is_null() || overlay.rect_count == 0 {
        return;
    }
    unsafe {
        drop(Box::from_raw(std::ptr::slice_from_raw_parts_mut(
            overlay.rects as *mut SyoRect,
            overlay.rect_count,
        )));
    }
}

/// PDF lifecycle of a highlight annotation record (`0` Pending, `1` Embedded,
/// `2` External). Integer rather than a Rust enum so the C names match the
/// documented ABI without fighting Rust naming conventions.
pub type SyoHighlightState = i32;
pub const SYO_HIGHLIGHT_PENDING: SyoHighlightState = 0;
pub const SYO_HIGHLIGHT_EMBEDDED: SyoHighlightState = 1;
pub const SYO_HIGHLIGHT_EXTERNAL: SyoHighlightState = 2;

fn syo_highlight_state(state: HighlightPdfState) -> SyoHighlightState {
    match state {
        HighlightPdfState::Pending => SYO_HIGHLIGHT_PENDING,
        HighlightPdfState::Embedded => SYO_HIGHLIGHT_EMBEDDED,
        HighlightPdfState::External => SYO_HIGHLIGHT_EXTERNAL,
    }
}

/// One highlight for the annotations sidebar. `text` and `color` are owned heap
/// copies; free the whole list with [`syo_highlight_list_free`]. Pages are
/// zero-based (the shell displays them one-based).
#[repr(C)]
pub struct SyoHighlightItem {
    pub id: i64,
    pub first_page: usize,
    pub last_page: usize,
    pub text: *mut c_char,
    pub color: *mut c_char,
    pub state: SyoHighlightState,
}

/// Annotation snapshot for the open document. Owned by the caller; free with
/// [`syo_highlight_list_free`].
#[repr(C)]
pub struct SyoHighlightList {
    pub items: *mut SyoHighlightItem,
    pub count: usize,
    pub revision: u64,
}

fn empty_highlight_list(revision: u64) -> *mut SyoHighlightList {
    Box::into_raw(Box::new(SyoHighlightList {
        items: std::ptr::null_mut(),
        count: 0,
        revision,
    }))
}

/// Every highlight of the open document (Pending and Embedded), in document
/// order. Distinct from [`syo_app_highlights`], which returns screen-space
/// overlay geometry for Pending records only. Free with
/// [`syo_highlight_list_free`].
///
/// # Safety
/// `app` must be NULL or valid.
#[no_mangle]
pub unsafe extern "C" fn syo_app_highlight_list(app: *const SyoApp) -> *mut SyoHighlightList {
    let Some(app) = (unsafe { app.as_ref() }) else {
        return empty_highlight_list(0);
    };
    catch_unwind(AssertUnwindSafe(|| {
        let revision = app.app.annotation_revision();
        let summaries = app.app.highlight_summaries();
        if summaries.is_empty() {
            return empty_highlight_list(revision);
        }
        let mut items: Vec<SyoHighlightItem> = summaries
            .into_iter()
            .map(|s| SyoHighlightItem {
                id: s.id.0,
                first_page: s.first_page,
                last_page: s.last_page,
                text: to_c_string(s.text),
                color: to_c_string(s.color),
                state: syo_highlight_state(s.pdf_state),
            })
            .collect();
        let count = items.len();
        let items_ptr = items.as_mut_ptr();
        std::mem::forget(items);
        Box::into_raw(Box::new(SyoHighlightList {
            items: items_ptr,
            count,
            revision,
        }))
    }))
    .unwrap_or_else(|_| empty_highlight_list(0))
}

/// Free a list returned by [`syo_app_highlight_list`]. A no-op for NULL.
///
/// # Safety
/// `list` must be NULL or a pointer returned by [`syo_app_highlight_list`],
/// not freed before.
#[no_mangle]
pub unsafe extern "C" fn syo_highlight_list_free(list: *mut SyoHighlightList) {
    if list.is_null() {
        return;
    }
    let _ = catch_unwind(AssertUnwindSafe(|| unsafe {
        let list = Box::from_raw(list);
        if !list.items.is_null() && list.count > 0 {
            let items = Box::from_raw(std::ptr::slice_from_raw_parts_mut(list.items, list.count));
            for item in items.iter() {
                syo_string_free(item.text);
                syo_string_free(item.color);
            }
        }
    }));
}

