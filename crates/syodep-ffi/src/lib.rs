#[no_mangle]
pub extern "C" fn syo_default_config_path() -> *mut c_char {
    to_c_string(
        default_base_dir("XDG_CONFIG_HOME", ".config")
            .join("syodep")
            .join("config.toml")
            .display()
            .to_string(),
    )
}

/// Documented default configuration as TOML text: every option set to its
/// built-in default. Written to disk by the shell's `--defaults`. Free with
/// `syo_string_free`.
#[no_mangle]
pub extern "C" fn syo_default_config_toml() -> *mut c_char {
    to_c_string(syodep_config::default_config_doc())
}

/// Default database path for this platform. Free with `syo_string_free`.
#[no_mangle]
pub extern "C" fn syo_default_db_path() -> *mut c_char {
    to_c_string(
        default_base_dir("XDG_DATA_HOME", ".local/share")
            .join("syodep")
            .join("syodep.sqlite3")
            .display()
            .to_string(),
    )
}

/// Resolve a per-user base directory without extra dependencies.
/// Windows uses %APPDATA%; Unix follows the XDG spec with its fallbacks.
fn default_base_dir(xdg_var: &str, unix_fallback: &str) -> PathBuf {
    #[cfg(windows)]
    {
        let _ = (xdg_var, unix_fallback);
        if let Some(appdata) = std::env::var_os("APPDATA") {
            return PathBuf::from(appdata);
        }
        return PathBuf::from(".");
    }
    #[cfg(not(windows))]
    {
        if let Some(dir) = std::env::var_os(xdg_var) {
            let path = PathBuf::from(dir);
            if path.is_absolute() {
                return path;
            }
        }
        if let Some(home) = std::env::var_os("HOME") {
            return std::path::Path::new(&home).join(unix_fallback);
        }
        PathBuf::from(".")
    }
}

